-- CHUONG Phase 4O1: Cover A/B experiments for authors.
begin;

create table if not exists public.book_cover_experiments (
  id uuid primary key default gen_random_uuid(),
  book_id uuid not null references public.books(id) on delete cascade,
  variant_a_url text not null,
  variant_b_url text not null,
  status text not null default 'running' check (status in ('running','completed','cancelled')),
  winner_variant text null check (winner_variant in ('A','B')),
  started_at timestamptz not null default now(),
  ended_at timestamptz null,
  created_by uuid null references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists book_cover_experiments_one_running_idx
  on public.book_cover_experiments(book_id)
  where status = 'running';

create index if not exists book_cover_experiments_book_created_idx
  on public.book_cover_experiments(book_id, created_at desc);

create table if not exists public.book_cover_experiment_events (
  id bigint generated by default as identity primary key,
  experiment_id uuid not null references public.book_cover_experiments(id) on delete cascade,
  subject_hash text not null,
  variant text not null check (variant in ('A','B')),
  event_type text not null check (event_type in ('impression','click')),
  created_at timestamptz not null default now(),
  unique(experiment_id, subject_hash, event_type)
);

create index if not exists book_cover_experiment_events_exp_idx
  on public.book_cover_experiment_events(experiment_id, event_type, variant);

alter table public.book_cover_experiments enable row level security;
alter table public.book_cover_experiment_events enable row level security;

drop policy if exists "public reads active cover experiments" on public.book_cover_experiments;
create policy "public reads active cover experiments"
on public.book_cover_experiments
for select
to anon, authenticated
using (
  status = 'running'
  and exists (
    select 1
    from public.books b
    join public.authors a on a.id = b.author_id
    where b.id = book_id
      and b.visibility = 'public'
      and b.status <> 'draft'
      and b.moderation_state = 'approved'
      and a.moderation_state = 'approved'
  )
);

drop policy if exists "authors read own cover experiments" on public.book_cover_experiments;
create policy "authors read own cover experiments"
on public.book_cover_experiments
for select
to authenticated
using (
  exists (
    select 1
    from public.books b
    join public.authors a on a.id = b.author_id
    where b.id = book_id
      and (
        a.user_id = (select auth.uid())
        or (select private.is_admin())
      )
  )
);

revoke all privileges on table public.book_cover_experiment_events from anon, authenticated;
revoke insert, update, delete on table public.book_cover_experiments from anon, authenticated;
grant select on table public.book_cover_experiments to anon, authenticated;

create or replace function private.cover_experiment_variant(p_experiment_id uuid, p_install_id text)
returns text
language sql
immutable
set search_path = ''
as $$
  select case
    when lower(substr(md5(p_experiment_id::text || ':' || coalesce(p_install_id,'')), 1, 1)) in ('0','1','2','3','4','5','6','7')
      then 'A'
    else 'B'
  end;
$$;

revoke execute on function private.cover_experiment_variant(uuid,text) from public, anon, authenticated;

create or replace function public.get_active_cover_experiments(
  p_book_ids uuid[],
  p_install_id text
)
returns table (
  experiment_id uuid,
  book_id uuid,
  variant text,
  cover_url text
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    e.id as experiment_id,
    e.book_id,
    private.cover_experiment_variant(e.id, p_install_id) as variant,
    case private.cover_experiment_variant(e.id, p_install_id)
      when 'A' then e.variant_a_url
      else e.variant_b_url
    end as cover_url
  from public.book_cover_experiments e
  join public.books b on b.id = e.book_id
  join public.authors a on a.id = b.author_id
  where e.status = 'running'
    and e.book_id = any(coalesce(p_book_ids, array[]::uuid[]))
    and char_length(coalesce(p_install_id,'')) >= 8
    and b.visibility = 'public'
    and b.status <> 'draft'
    and b.moderation_state = 'approved'
    and a.moderation_state = 'approved';
$$;

revoke execute on function public.get_active_cover_experiments(uuid[],text) from public;
grant execute on function public.get_active_cover_experiments(uuid[],text) to anon, authenticated;

create or replace function public.record_cover_experiment_event(
  p_experiment_id uuid,
  p_install_id text,
  p_event_type text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_exp public.book_cover_experiments%rowtype;
  v_variant text;
begin
  if char_length(coalesce(p_install_id,'')) < 8 then return false; end if;
  if p_event_type not in ('impression','click') then return false; end if;

  select * into v_exp
  from public.book_cover_experiments e
  where e.id = p_experiment_id and e.status = 'running';

  if not found then return false; end if;

  if not exists (
    select 1
    from public.books b
    join public.authors a on a.id = b.author_id
    where b.id = v_exp.book_id
      and b.visibility = 'public'
      and b.status <> 'draft'
      and b.moderation_state = 'approved'
      and a.moderation_state = 'approved'
  ) then
    return false;
  end if;

  v_variant := private.cover_experiment_variant(v_exp.id, p_install_id);

  insert into public.book_cover_experiment_events(
    experiment_id, subject_hash, variant, event_type
  ) values (
    v_exp.id,
    md5('cover-exp-v1:' || p_install_id),
    v_variant,
    p_event_type
  )
  on conflict (experiment_id, subject_hash, event_type) do nothing;

  return true;
end;
$$;

revoke execute on function public.record_cover_experiment_event(uuid,text,text) from public;
grant execute on function public.record_cover_experiment_event(uuid,text,text) to anon, authenticated;

create or replace function public.start_book_cover_experiment(
  p_book_id uuid,
  p_variant_b_url text
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_book public.books%rowtype;
  v_author public.authors%rowtype;
  v_id uuid;
begin
  if v_uid is null then raise exception 'AUTH_REQUIRED' using errcode='42501'; end if;

  select * into v_book from public.books where id = p_book_id;
  if not found then raise exception 'BOOK_NOT_FOUND'; end if;
  select * into v_author from public.authors where id = v_book.author_id;
  if not found then raise exception 'AUTHOR_NOT_FOUND'; end if;

  if v_author.user_id <> v_uid and not (select private.is_admin()) then
    raise exception 'FORBIDDEN' using errcode='42501';
  end if;

  if v_book.cover_url is null or char_length(btrim(v_book.cover_url)) < 8 then
    raise exception 'COVER_A_REQUIRED';
  end if;
  if char_length(coalesce(btrim(p_variant_b_url),'')) < 8 then
    raise exception 'COVER_B_REQUIRED';
  end if;
  if btrim(p_variant_b_url) = btrim(v_book.cover_url) then
    raise exception 'COVERS_MUST_DIFFER';
  end if;
  if exists (
    select 1 from public.book_cover_experiments
    where book_id = p_book_id and status = 'running'
  ) then
    raise exception 'ACTIVE_EXPERIMENT_EXISTS';
  end if;

  insert into public.book_cover_experiments(
    book_id, variant_a_url, variant_b_url, status, started_at, created_by
  ) values (
    p_book_id, btrim(v_book.cover_url), btrim(p_variant_b_url), 'running', now(), v_uid
  )
  returning id into v_id;

  return v_id;
end;
$$;

revoke execute on function public.start_book_cover_experiment(uuid,text) from public, anon;
grant execute on function public.start_book_cover_experiment(uuid,text) to authenticated;

create or replace function public.finish_book_cover_experiment(
  p_experiment_id uuid,
  p_winner_variant text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_exp public.book_cover_experiments%rowtype;
  v_book public.books%rowtype;
  v_author public.authors%rowtype;
  v_cover text;
begin
  if v_uid is null then raise exception 'AUTH_REQUIRED' using errcode='42501'; end if;
  if p_winner_variant not in ('A','B') then raise exception 'INVALID_WINNER'; end if;

  select * into v_exp
  from public.book_cover_experiments
  where id = p_experiment_id
  for update;
  if not found then raise exception 'EXPERIMENT_NOT_FOUND'; end if;
  if v_exp.status <> 'running' then raise exception 'EXPERIMENT_NOT_RUNNING'; end if;

  select * into v_book from public.books where id = v_exp.book_id;
  select * into v_author from public.authors where id = v_book.author_id;

  if v_author.user_id <> v_uid and not (select private.is_admin()) then
    raise exception 'FORBIDDEN' using errcode='42501';
  end if;

  v_cover := case p_winner_variant when 'A' then v_exp.variant_a_url else v_exp.variant_b_url end;

  update public.books
  set cover_url = v_cover, updated_at = now()
  where id = v_exp.book_id;

  update public.book_cover_experiments
  set status='completed',
      winner_variant=p_winner_variant,
      ended_at=now(),
      updated_at=now()
  where id=p_experiment_id;

  return true;
end;
$$;

revoke execute on function public.finish_book_cover_experiment(uuid,text) from public, anon;
grant execute on function public.finish_book_cover_experiment(uuid,text) to authenticated;

create or replace function public.cancel_book_cover_experiment(
  p_experiment_id uuid
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_exp public.book_cover_experiments%rowtype;
  v_book public.books%rowtype;
  v_author public.authors%rowtype;
begin
  if v_uid is null then raise exception 'AUTH_REQUIRED' using errcode='42501'; end if;

  select * into v_exp
  from public.book_cover_experiments
  where id = p_experiment_id
  for update;
  if not found then raise exception 'EXPERIMENT_NOT_FOUND'; end if;
  if v_exp.status <> 'running' then return true; end if;

  select * into v_book from public.books where id = v_exp.book_id;
  select * into v_author from public.authors where id = v_book.author_id;
  if v_author.user_id <> v_uid and not (select private.is_admin()) then
    raise exception 'FORBIDDEN' using errcode='42501';
  end if;

  update public.book_cover_experiments
  set status='cancelled', ended_at=now(), updated_at=now()
  where id=p_experiment_id;

  return true;
end;
$$;

revoke execute on function public.cancel_book_cover_experiment(uuid) from public, anon;
