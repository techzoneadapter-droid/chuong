create or replace function public.get_author_cover_experiments(
  p_author_id uuid
)
returns table (
  experiment_id uuid,
  book_id uuid,
  title text,
  variant_a_url text,
  variant_b_url text,
  status text,
  winner_variant text,
  started_at timestamptz,
  ended_at timestamptz,
  impressions_a bigint,
  impressions_b bigint,
  clicks_a bigint,
  clicks_b bigint,
  ctr_a numeric,
  ctr_b numeric
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
begin
  if v_uid is null then raise exception 'AUTH_REQUIRED' using errcode='42501'; end if;
  if not exists (
    select 1 from public.authors a
    where a.id = p_author_id
      and (a.user_id = v_uid or (select private.is_admin()))
  ) then
    raise exception 'FORBIDDEN' using errcode='42501';
  end if;

  return query
  select
    e.id,
    e.book_id,
    b.title,
    e.variant_a_url,
    e.variant_b_url,
    e.status,
    e.winner_variant,
    e.started_at,
    e.ended_at,
    count(ev.id) filter (where ev.event_type='impression' and ev.variant='A')::bigint,
    count(ev.id) filter (where ev.event_type='impression' and ev.variant='B')::bigint,
    count(ev.id) filter (where ev.event_type='click' and ev.variant='A')::bigint,
    count(ev.id) filter (where ev.event_type='click' and ev.variant='B')::bigint,
    case
      when count(ev.id) filter (where ev.event_type='impression' and ev.variant='A') = 0 then 0::numeric
      else round(
        100.0 * count(ev.id) filter (where ev.event_type='click' and ev.variant='A')
        / count(ev.id) filter (where ev.event_type='impression' and ev.variant='A'),
        2
      )
    end,
    case
      when count(ev.id) filter (where ev.event_type='impression' and ev.variant='B') = 0 then 0::numeric
      else round(
        100.0 * count(ev.id) filter (where ev.event_type='click' and ev.variant='B')
        / count(ev.id) filter (where ev.event_type='impression' and ev.variant='B'),
        2
      )
    end
  from public.book_cover_experiments e
  join public.books b on b.id=e.book_id
  left join public.book_cover_experiment_events ev on ev.experiment_id=e.id
  where b.author_id=p_author_id
  group by e.id,b.title
  order by e.created_at desc;
end;
$$;

revoke execute on function public.get_author_cover_experiments(uuid) from public, anon;
grant execute on function public.get_author_cover_experiments(uuid) to authenticated;

